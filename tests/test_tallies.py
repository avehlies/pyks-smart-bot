async def test_topmail_ranks_skips_bot_posts_and_clips(
    bot: YKSBot, guild: FakeGuild, mailbag: FakeChannel, general: FakeChannel
) -> None:
    alice, bob = FakeUser(name="alice"), FakeUser(name="bob")
    long_letter = mailbag.post("x" * 2000, author=bob)
    by_bot = mailbag.post("bot post", author=FakeUser(id=BOT_USER_ID, bot=True))
    short_letter = mailbag.post("Love the show", author=alice)
    for message, count in ((long_letter, 3), (by_bot, 9), (short_letter, 5)):
        await cog(bot).refresh_tally(react(message, count))

    await say(bot, general, "!topmail", FakeUser())
    (embed,) = general.embeds
    assert embed.title == "__Top Mailbag Messages (Last 30 Days)__\n"
    assert [f.name for f in embed.fields] == ["1. From alice", "2. From bob"]
    assert embed.fields[0].value == f"[Jump to message]({short_letter.jump_url})\nLove the show"
    assert len(embed.fields[1].value) == 1024
    assert embed.fields[1].value.endswith("...")


async def test_topmail_limits_to_ten_and_last_30_days(
    bot: YKSBot, db: Database, guild: FakeGuild, mailbag: FakeChannel, general: FakeChannel
) -> None:
    letters = [mailbag.post(f"letter {i}", author=FakeUser(name=f"u{i}")) for i in range(12)]
    for i, letter in enumerate(letters):
        await cog(bot).refresh_tally(react(letter, i + 1))
    old = mailbag.post("ancient", created_at=NOW - timedelta(days=45))
    async with db.session() as session:  # a stale row the daily cleanup hasn't removed yet
        await set_tally(
            session,
            kind=TallyKind.MAILBAG,
            guild_id=guild.id,
            channel_id=mailbag.id,
            message_id=old.id,
            message_created_at=old.created_at,
            count=99,
        )
    await say(bot, general, "!bestmail", FakeUser())
    names = [f.name for f in general.embeds[0].fields]
    assert names == [f"{n}. From u{11 - (n - 1)}" for n in range(1, 11)]


