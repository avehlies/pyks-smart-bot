async def test_prune_removes_only_old_mailbag_tallies(
    bot: YKSBot, db: Database, guild: FakeGuild, mailbag: FakeChannel, ks_channel: FakeChannel
) -> None:
    rows = [
        (TallyKind.MAILBAG, mailbag.id, NOW - timedelta(days=31)),
        (TallyKind.MAILBAG, mailbag.id, NOW - timedelta(days=29)),
        (TallyKind.KICKSTARTER, ks_channel.id, NOW - timedelta(days=400)),  # kept forever
    ]
    async with db.session() as session:
        for message_id, (kind, channel_id, created) in enumerate(rows, start=1):
            await set_tally(
                session,
                kind=kind,
                guild_id=guild.id,
                channel_id=channel_id,
                message_id=message_id,
                message_created_at=created,
                count=1,
            )
    assert await cog(bot).prune_old_mailbag() == 1
    async with db.session() as session:
        remaining = sorted((await session.scalars(select(ReactionTally.message_id))).all())
    assert remaining == [2, 3]
