""":this: reaction tallies: mailbag messages and generated kickstarters, !topmail, !topks."""

from __future__ import annotations

import logging
from datetime import UTC, datetime, time, timedelta
from typing import TYPE_CHECKING, Any

import discord
from discord.ext import commands, tasks

from yks.bot.checks import HOUR, akairo_cooldown
from yks.db import ReactionTally, TallyKind
from yks.db.tallies import delete_tally, prune_older_than, set_tally, top_tallies

if TYPE_CHECKING:
    from yks.bot.client import YKSBot

log = logging.getLogger(__name__)

THIS_EMOJI = "this"
GREEN = 0x83C133
TOP_N = 10
MAILBAG_WINDOW = timedelta(days=30)
FIELD_VALUE_LIMIT = 1024


def ellipsis(text: str, limit: int = FIELD_VALUE_LIMIT) -> str:
    """Like the `text-ellipsis` package: at most `limit` characters, ending in '...' if cut."""
    return text if len(text) <= limit else text[: limit - 3] + "..."


def this_count(message: discord.Message) -> int:
    """How many users reacted with the :this: emoji (custom or not)."""
    for reaction in message.reactions:
        if getattr(reaction.emoji, "name", reaction.emoji) == THIS_EMOJI:
            return reaction.count
    return 0


class Tallies(commands.Cog):
    def __init__(self, bot: YKSBot) -> None:
        self.bot = bot

    async def cog_load(self) -> None:
        self.prune_mailbag.start()

    async def cog_unload(self) -> None:
        self.prune_mailbag.cancel()

    # --- reaction events ------------------------------------------------------------------------

    @commands.Cog.listener()
    async def on_raw_reaction_add(self, payload: discord.RawReactionActionEvent) -> None:
        await self.refresh_tally(payload)

    @commands.Cog.listener()
    async def on_raw_reaction_remove(self, payload: discord.RawReactionActionEvent) -> None:
        await self.refresh_tally(payload)

    def _kind_for_channel(self, channel_id: int) -> TallyKind | None:
        settings = self.bot.settings
        if settings.yks_mailbag_channel_id and channel_id == settings.yks_mailbag_channel_id:
            return TallyKind.MAILBAG
        if (
            settings.yks_kickstarter_bot_channel_id
            and channel_id == settings.yks_kickstarter_bot_channel_id
        ):
            return TallyKind.KICKSTARTER
        return None

    async def _channel(self, channel_id: int) -> Any | None:
        channel = self.bot.get_channel(channel_id)
        if channel is None:
            try:
                channel = await self.bot.fetch_channel(channel_id)
            except discord.HTTPException:
                return None
        return channel

    async def refresh_tally(self, payload: discord.RawReactionActionEvent) -> bool:
        """Re-read the message's real :this: count and store it.

        The TS bot added or subtracted 1 per event, so any missed event left the tally wrong for
        good. Reading the count from Discord makes every event correct the stored value.
        Returns True if a tally was written or removed.
        """
        if payload.emoji.name != THIS_EMOJI or payload.guild_id is None:
            return False
        kind = self._kind_for_channel(payload.channel_id)
        if kind is None:
            return False
        channel = await self._channel(payload.channel_id)
        if channel is None:
            return False
        try:
            message = await channel.fetch_message(payload.message_id)
        except discord.NotFound:
            async with self.bot.db.session() as session:
                await delete_tally(session, payload.message_id)
            return True
        except discord.HTTPException:
            log.warning("Could not fetch message %s for a :this: tally", payload.message_id)
            return False

        if kind is TallyKind.KICKSTARTER and not self._is_generated_kickstarter(message):
            return False
        async with self.bot.db.session() as session:
            await set_tally(
                session,
                kind=kind,
                guild_id=payload.guild_id,
                channel_id=payload.channel_id,
                message_id=message.id,
                message_created_at=message.created_at,
                count=this_count(message),
            )
        return True

    def _is_generated_kickstarter(self, message: discord.Message) -> bool:
        """The bot's own kickstarter posts: an embed with a footer ("Output generated by...")."""
        return (
            self.bot.user is not None
            and message.author.id == self.bot.user.id
            and bool(message.embeds)
            and bool(message.embeds[0].footer and message.embeds[0].footer.text)
        )

    # --- daily cleanup --------------------------------------------------------------------------

    @tasks.loop(time=time(hour=9, tzinfo=UTC))  # once a day; also runs once at startup
    async def prune_mailbag(self) -> None:
        await self.prune_old_mailbag()

    @prune_mailbag.before_loop
    async def _before_prune(self) -> None:
        await self.bot.wait_until_ready()
        await self.prune_old_mailbag()

    async def prune_old_mailbag(self) -> int:
        cutoff = datetime.now(UTC) - MAILBAG_WINDOW
        async with self.bot.db.session() as session:
            removed = await prune_older_than(session, TallyKind.MAILBAG, cutoff)
        log.info("Cleared %d mailbag tallies older than 30 days.", removed)
        return removed

    # --- listings ---------------------------------------------------------------------------------

    async def _fetch_listed(self, tally: ReactionTally) -> discord.Message | None:
        """Fetch a tallied message; forget the tally if the message is gone."""
        channel = await self._channel(tally.channel_id)
        if channel is None:
            return None
        try:
            return await channel.fetch_message(tally.message_id)
        except discord.NotFound:
            async with self.bot.db.session() as session:
                await delete_tally(session, tally.message_id)
        except discord.HTTPException:
            log.warning("Could not fetch tallied message %s", tally.message_id)
        return None

    @commands.command(name="topmailbag", aliases=["topmail", "bestmailbag", "bestmail"])
    @commands.guild_only()
    @akairo_cooldown(HOUR)
    async def top_mailbag(self, ctx: commands.Context[Any]) -> None:
        assert ctx.guild is not None
        since = datetime.now(UTC) - MAILBAG_WINDOW
        async with self.bot.db.session() as session:
            candidates = await top_tallies(session, TallyKind.MAILBAG, ctx.guild.id, since=since)
        embed = discord.Embed(color=GREEN, title="__Top Mailbag Messages (Last 30 Days)__\n")
        for tally in candidates:
            if len(embed.fields) == TOP_N:
                break
            message = await self._fetch_listed(tally)
            if message is None or (self.bot.user and message.author.id == self.bot.user.id):
                continue  # the bot's own posts don't count
            embed.add_field(
                name=f"{len(embed.fields) + 1}. From {message.author.name}",
                value=ellipsis(f"[Jump to message]({message.jump_url})\n{message.content}"),
                inline=False,
            )
        if not embed.fields:
            await ctx.send("No mailbag messages with :this: reactions in the last 30 days.")
            return
        await ctx.send(embed=embed)

    @commands.command(name="topkickstarters", aliases=["bestkickstarters", "topks", "bestks"])
    @commands.guild_only()
    @akairo_cooldown(HOUR)
    async def top_kickstarters(self, ctx: commands.Context[Any]) -> None:
        assert ctx.guild is not None
        async with self.bot.db.session() as session:
            candidates = await top_tallies(session, TallyKind.KICKSTARTER, ctx.guild.id)
        entries: list[tuple[str, str]] = []
        for tally in candidates:
            if len(entries) == TOP_N:
                break
            message = await self._fetch_listed(tally)
            if message is None or not message.embeds:
                continue
            generated = message.embeds[0]
            entries.append(
                (
                    f"{len(entries) + 1}: {generated.title or 'Untitled'}"[:256],
                    ellipsis(
                        f"[Jump to message]({message.jump_url})\n{generated.description or ''}"
                    ),
                )
            )
        if not entries:
            return  # like the TS bot: nothing to show, no reply
        embed = discord.Embed(color=GREEN, title=f"__Top {len(entries)} Kickstarters__\n")
        for name, value in entries:
            embed.add_field(name=name, value=value, inline=False)
        await ctx.send(embed=embed)


async def setup(bot: YKSBot) -> None:
    await bot.add_cog(Tallies(bot))
